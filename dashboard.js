function openMission(missionNumber) {
    if (missionNumber === 1) {
        window.location.href = "mission-1-selected.html";
    }

    else if (missionNumber === 2) {
        window.location.href = "mission-2-selected.html";
    }

    else if (missionNumber === 3) {
        window.location.href = "mission-3-selected.html";
    }
}